const near = (p: string) => `${p}-თან ახლოს`;
const onto = (road?: string) => (road ? `, ${road}-ზე` : '');
const ordinal = (n: number) =>
  ['პირველ', 'მეორე', 'მესამე', 'მეოთხე', 'მეხუთე', 'მეექვსე', 'მეშვიდე', 'მერვე', 'მეცხრე', 'მეათე'][n - 1] ?? `მე-${n}`;

